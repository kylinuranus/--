from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from project_paths import SCREENING_RESULTS_DIR, ensure_project_dirs


DATA_ROOT = Path(r"D:\a_stock_data")
DAILY_COLUMNS = ["open", "high", "low", "close"]
ALL_GROUPS = ("three_day_all", "two_day_all", "both", "three_day_only", "two_day_only")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Analyze next-day red candle that holds the signal-day low, "
            "then buy at next-day close and sell at following close."
        )
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=SCREENING_RESULTS_DIR / "weekly_bullish_kong_turn_bull_forward_compare_detail_2026-04-01_to_2026-06-30.csv",
        help="Signal detail CSV generated by kong_turn_bull_forward_compare.py.",
    )
    parser.add_argument("--data-root", type=Path, default=DATA_ROOT, help="Local parquet root.")
    parser.add_argument("--output-dir", type=Path, default=SCREENING_RESULTS_DIR, help="Directory for outputs.")
    return parser.parse_args()


def compute_return(current: float | int | None, base: float | int | None) -> float | None:
    if current is None or base is None or pd.isna(current) or pd.isna(base):
        return None
    base_float = float(base)
    if abs(base_float) <= 1e-9:
        return None
    return float(current) / base_float - 1.0


def format_pct(value: float | None, digits: int = 2) -> str:
    if value is None or pd.isna(value):
        return "-"
    return f"{value * 100:.{digits}f}%"


def bool_series(series: pd.Series) -> pd.Series:
    if series.dtype == bool:
        return series.fillna(False)
    return series.astype(str).str.lower().isin(["true", "1", "yes"])


def build_entry_detail(signal_df: pd.DataFrame, data_root: Path) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    daily_root = data_root / "daily"
    daily_cache: dict[str, pd.DataFrame] = {}

    for signal in signal_df.itertuples(index=False):
        file_symbol = str(signal.file_symbol)
        daily_df = daily_cache.get(file_symbol)
        if daily_df is None:
            daily_path = daily_root / f"{file_symbol}.parquet"
            if not daily_path.exists():
                continue
            daily_df = pd.read_parquet(daily_path, columns=DAILY_COLUMNS).sort_index()
            daily_cache[file_symbol] = daily_df

        daily_dates = pd.to_datetime(daily_df.index).normalize()
        signal_date = pd.Timestamp(signal.signal_date).normalize()
        signal_matches = [idx for idx, value in enumerate(daily_dates) if pd.Timestamp(value).normalize() == signal_date]
        if not signal_matches:
            continue

        signal_idx = signal_matches[0]
        entry_idx = signal_idx + 1
        exit_idx = entry_idx + 1
        if exit_idx >= len(daily_df):
            continue

        entry_bar = daily_df.iloc[entry_idx]
        exit_bar = daily_df.iloc[exit_idx]
        signal_low = float(signal.signal_low)
        entry_open = float(entry_bar["open"])
        entry_high = float(entry_bar["high"])
        entry_low = float(entry_bar["low"])
        entry_close = float(entry_bar["close"])

        next_day_red = entry_close < entry_open
        next_day_holds_signal_low = entry_low >= signal_low
        if not (next_day_red and next_day_holds_signal_low):
            continue

        exit_close = float(exit_bar["close"])
        rows.append(
            {
                "file_symbol": file_symbol,
                "symbol": str(signal.symbol),
                "name": str(signal.name),
                "signal_date": signal_date.date().isoformat(),
                "signal_month": str(signal.signal_month),
                "kong_turn_bull_pattern": getattr(signal, "kong_turn_bull_pattern"),
                "three_day_kong_turn_bull": bool(getattr(signal, "three_day_kong_turn_bull")),
                "two_day_kong_turn_bull": bool(getattr(signal, "two_day_kong_turn_bull")),
                "signal_open": float(signal.signal_open),
                "signal_high": float(signal.signal_high),
                "signal_low": signal_low,
                "signal_close": float(signal.signal_close),
                "entry_date": pd.Timestamp(daily_dates[entry_idx]).date().isoformat(),
                "entry_open": entry_open,
                "entry_high": entry_high,
                "entry_low": entry_low,
                "entry_close": entry_close,
                "entry_day_red": True,
                "entry_day_holds_signal_low": True,
                "entry_low_vs_signal_low_ret": compute_return(entry_low, signal_low),
                "entry_close_vs_signal_close_ret": compute_return(entry_close, float(signal.signal_close)),
                "exit_date": pd.Timestamp(daily_dates[exit_idx]).date().isoformat(),
                "exit_close": exit_close,
                "next_close_return": compute_return(exit_close, entry_close),
                "next_close_up": exit_close > entry_close,
            }
        )

    result_df = pd.DataFrame(rows)
    if not result_df.empty:
        result_df = result_df.sort_values(["signal_date", "file_symbol"]).reset_index(drop=True)
    return result_df


def expand_groups(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return pd.DataFrame()

    three_day = bool_series(df["three_day_kong_turn_bull"])
    two_day = bool_series(df["two_day_kong_turn_bull"])
    group_masks = [
        ("three_day_all", three_day),
        ("two_day_all", two_day),
        ("both", three_day & two_day),
        ("three_day_only", three_day & ~two_day),
        ("two_day_only", two_day & ~three_day),
    ]

    frames: list[pd.DataFrame] = []
    for group_name, mask in group_masks:
        subset = df.loc[mask].copy()
        if subset.empty:
            continue
        subset["group_name"] = group_name
        frames.append(subset)
    if not frames:
        return pd.DataFrame()
    return pd.concat(frames, ignore_index=True)


def summarize_return_series(series: pd.Series) -> dict[str, object]:
    numeric = pd.to_numeric(series, errors="coerce").dropna()
    if numeric.empty:
        return {
            "sample_count": 0,
            "win_rate": pd.NA,
            "avg_return": pd.NA,
            "median_return": pd.NA,
            "avg_gain": pd.NA,
            "avg_loss": pd.NA,
        }

    gains = numeric[numeric > 0]
    losses = numeric[numeric <= 0]
    return {
        "sample_count": int(len(numeric)),
        "win_rate": float((numeric > 0).mean()),
        "avg_return": float(numeric.mean()),
        "median_return": float(numeric.median()),
        "avg_gain": float(gains.mean()) if not gains.empty else pd.NA,
        "avg_loss": float(losses.mean()) if not losses.empty else pd.NA,
    }


def build_summary(grouped_entry_df: pd.DataFrame) -> pd.DataFrame:
    if grouped_entry_df.empty:
        return pd.DataFrame()

    rows: list[dict[str, object]] = []
    for group_name, group_df in grouped_entry_df.groupby("group_name", sort=False):
        rows.append(
            {
                "scope": "overall",
                "signal_month": pd.NA,
                "group_name": group_name,
                **summarize_return_series(group_df["next_close_return"]),
            }
        )
        for signal_month, month_df in group_df.groupby("signal_month", sort=True):
            rows.append(
                {
                    "scope": "monthly",
                    "signal_month": signal_month,
                    "group_name": group_name,
                    **summarize_return_series(month_df["next_close_return"]),
                }
            )

    return pd.DataFrame(rows).sort_values(["scope", "signal_month", "group_name"], na_position="first").reset_index(drop=True)


def build_condition_summary(signal_df: pd.DataFrame, entry_df: pd.DataFrame) -> pd.DataFrame:
    grouped_signals = expand_groups(signal_df)
    grouped_entries = expand_groups(entry_df)
    months = sorted(signal_df["signal_month"].dropna().unique())
    rows: list[dict[str, object]] = []

    for scope, month in [("overall", pd.NA)] + [("monthly", value) for value in months]:
        for group_name in ALL_GROUPS:
            signal_subset = grouped_signals[grouped_signals["group_name"] == group_name]
            entry_subset = grouped_entries[grouped_entries["group_name"] == group_name]
            if scope == "monthly":
                signal_subset = signal_subset[signal_subset["signal_month"] == month]
                entry_subset = entry_subset[entry_subset["signal_month"] == month]

            signal_count = len(signal_subset)
            entry_count = len(entry_subset)
            rows.append(
                {
                    "scope": scope,
                    "signal_month": month,
                    "group_name": group_name,
                    "signal_count": signal_count,
                    "condition_count": entry_count,
                    "condition_rate": float(entry_count / signal_count) if signal_count else pd.NA,
                }
            )

    return pd.DataFrame(rows)


def make_markdown_table(df: pd.DataFrame, columns: list[str], rename_map: dict[str, str] | None = None) -> str:
    if df.empty:
        return "无数据。"

    work_df = df.loc[:, columns].rename(columns=rename_map or {}).copy()
    headers = list(work_df.columns)
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for _, row in work_df.iterrows():
        cells = [str(row[column]) if not pd.isna(row[column]) else "-" for column in headers]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_condition_table(condition_df: pd.DataFrame) -> str:
    work_df = condition_df.copy()
    if work_df.empty:
        return "无数据。"

    work_df["condition_rate_text"] = work_df["condition_rate"].apply(format_pct)
    return make_markdown_table(
        work_df,
        columns=["group_name", "signal_count", "condition_count", "condition_rate_text"],
        rename_map={
            "group_name": "分组",
            "signal_count": "信号数",
            "condition_count": "触发买入数",
            "condition_rate_text": "触发率",
        },
    )


def render_return_table(summary_df: pd.DataFrame) -> str:
    work_df = summary_df.copy()
    if work_df.empty:
        return "无数据。"

    work_df["胜率"] = work_df["win_rate"].apply(format_pct)
    work_df["平均收益"] = work_df["avg_return"].apply(format_pct)
    work_df["中位收益"] = work_df["median_return"].apply(format_pct)
    work_df["平均盈利"] = work_df["avg_gain"].apply(format_pct)
    work_df["平均亏损"] = work_df["avg_loss"].apply(format_pct)
    return make_markdown_table(
        work_df,
        columns=["group_name", "sample_count", "胜率", "平均收益", "中位收益", "平均盈利", "平均亏损"],
        rename_map={"group_name": "分组", "sample_count": "样本数"},
    )


def build_report(
    signal_df: pd.DataFrame,
    entry_df: pd.DataFrame,
    condition_df: pd.DataFrame,
    summary_df: pd.DataFrame,
    output_paths: dict[str, Path],
) -> str:
    overall_condition = condition_df[condition_df["scope"] == "overall"].copy()
    overall_summary = summary_df[summary_df["scope"] == "overall"].copy()
    months = sorted(signal_df["signal_month"].dropna().unique())

    lines: list[str] = []
    lines.append("# 隔日收阴但不破信号日低点，尾盘买入后次日尾盘收益")
    lines.append("")
    lines.append("## 口径")
    lines.append("")
    lines.append("- 信号池：沿用 `weekly_bullish_kong_turn_bull_forward_compare_detail_2026-04-01_to_2026-06-30.csv`。")
    lines.append("- 买入条件：信号后第一个交易日收阴线，即 `close < open`，且当日最低价 `low >= 信号日 low`。")
    lines.append("- 买入价格：满足条件当天尾盘收盘价。")
    lines.append("- 卖出价格：买入后下一个交易日尾盘收盘价。")
    lines.append("- 收益口径：`下一个交易日收盘价 / 买入日收盘价 - 1`。")
    lines.append("")
    lines.append("## 整体触发情况")
    lines.append("")
    lines.append(f"- 原始信号数：{len(signal_df)}")
    lines.append(f"- 触发买入数：{len(entry_df)}")
    lines.append(f"- 整体触发率：{format_pct(len(entry_df) / len(signal_df)) if len(signal_df) else '-'}")
    lines.append("")
    lines.append(render_condition_table(overall_condition[overall_condition["group_name"].isin(ALL_GROUPS)]))
    lines.append("")
    lines.append("## 整体收益")
    lines.append("")
    lines.append(render_return_table(overall_summary[overall_summary["group_name"].isin(ALL_GROUPS)]))
    lines.append("")

    for month in months:
        month_condition = condition_df[(condition_df["scope"] == "monthly") & (condition_df["signal_month"] == month)].copy()
        month_summary = summary_df[(summary_df["scope"] == "monthly") & (summary_df["signal_month"] == month)].copy()
        lines.append(f"## {month}")
        lines.append("")
        lines.append(render_condition_table(month_condition[month_condition["group_name"].isin(ALL_GROUPS)]))
        lines.append("")
        lines.append(render_return_table(month_summary[month_summary["group_name"].isin(ALL_GROUPS)]))
        lines.append("")

    lines.append("## 输出文件")
    lines.append("")
    for label, path in output_paths.items():
        lines.append(f"- {label}: `{path.name}`")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    ensure_project_dirs()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    signal_df = pd.read_csv(args.input, dtype={"file_symbol": str, "symbol": str})
    entry_df = build_entry_detail(signal_df=signal_df, data_root=Path(args.data_root))
    grouped_entry_df = expand_groups(entry_df)
    condition_df = build_condition_summary(signal_df=signal_df, entry_df=entry_df)
    summary_df = build_summary(grouped_entry_df)

    suffix = args.input.stem.replace("weekly_bullish_kong_turn_bull_forward_compare_detail_", "")
    output_paths = {
        "entry_detail": output_dir / f"weekly_bullish_kong_turn_bull_nextday_red_holdlow_entry_detail_{suffix}.csv",
        "condition_summary": output_dir / f"weekly_bullish_kong_turn_bull_nextday_red_holdlow_entry_condition_{suffix}.csv",
        "return_summary": output_dir / f"weekly_bullish_kong_turn_bull_nextday_red_holdlow_entry_summary_{suffix}.csv",
        "report": output_dir / f"weekly_bullish_kong_turn_bull_nextday_red_holdlow_entry_report_{suffix}.md",
    }

    entry_df.to_csv(output_paths["entry_detail"], index=False, encoding="utf-8-sig")
    condition_df.to_csv(output_paths["condition_summary"], index=False, encoding="utf-8-sig")
    summary_df.to_csv(output_paths["return_summary"], index=False, encoding="utf-8-sig")
    output_paths["report"].write_text(
        build_report(
            signal_df=signal_df,
            entry_df=entry_df,
            condition_df=condition_df,
            summary_df=summary_df,
            output_paths=output_paths,
        ),
        encoding="utf-8",
    )

    print(f"signal_rows={len(signal_df)}")
    print(f"entry_rows={len(entry_df)}")
    print(f"entry_detail={output_paths['entry_detail']}")
    print(f"summary={output_paths['return_summary']}")
    print(f"report={output_paths['report']}")
    if not summary_df.empty:
        print(summary_df[summary_df["scope"] == "overall"].to_string(index=False))


if __name__ == "__main__":
    main()
