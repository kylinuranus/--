from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from project_paths import SCREENING_RESULTS_DIR, ensure_project_dirs


DATA_ROOT = Path(r"D:\a_stock_data")
HOLD_DAYS = (1, 2, 3, 4, 5)
ALL_GROUPS = ("three_day_all", "two_day_all", "both", "three_day_only", "two_day_only")
DAILY_COLUMNS = ["open", "high", "low", "close"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Analyze next-day 50% signal-K entry performance for two-day/three-day kong-turn-bull signals."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=SCREENING_RESULTS_DIR / "weekly_bullish_kong_turn_bull_forward_compare_detail_2026-04-01_to_2026-06-30.csv",
        help="Signal detail CSV generated by kong_turn_bull_forward_compare.py.",
    )
    parser.add_argument("--data-root", type=Path, default=DATA_ROOT, help="Local parquet root.")
    parser.add_argument("--output-dir", type=Path, default=SCREENING_RESULTS_DIR, help="Directory for outputs.")
    return parser.parse_args()


def compute_return(current: float | int | None, base: float | int | None) -> float | None:
    if current is None or base is None or pd.isna(current) or pd.isna(base):
        return None
    base_float = float(base)
    if abs(base_float) <= 1e-9:
        return None
    return float(current) / base_float - 1.0


def format_pct(value: float | None, digits: int = 2) -> str:
    if value is None or pd.isna(value):
        return "-"
    return f"{value * 100:.{digits}f}%"


def build_entry_detail(signal_df: pd.DataFrame, data_root: Path) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    daily_root = data_root / "daily"
    daily_cache: dict[str, pd.DataFrame] = {}

    for signal in signal_df.itertuples(index=False):
        file_symbol = str(signal.file_symbol)
        daily_df = daily_cache.get(file_symbol)
        if daily_df is None:
            daily_path = daily_root / f"{file_symbol}.parquet"
            if not daily_path.exists():
                continue
            daily_df = pd.read_parquet(daily_path, columns=DAILY_COLUMNS).sort_index()
            daily_cache[file_symbol] = daily_df

        daily_dates = pd.to_datetime(daily_df.index).normalize()
        signal_date = pd.Timestamp(signal.signal_date).normalize()
        matches = [idx for idx, value in enumerate(daily_dates) if pd.Timestamp(value).normalize() == signal_date]
        if not matches:
            continue

        signal_idx = matches[0]
        entry_idx = signal_idx + 1
        if entry_idx >= len(daily_df):
            continue

        entry_bar = daily_df.iloc[entry_idx]
        entry_date = pd.Timestamp(daily_dates[entry_idx]).date().isoformat()
        entry_price = float(signal.signal_low) + (float(signal.signal_high) - float(signal.signal_low)) * 0.5
        touched_entry = float(entry_bar["low"]) <= entry_price <= float(entry_bar["high"])
        if not touched_entry:
            continue

        row = {
            "file_symbol": file_symbol,
            "symbol": str(signal.symbol),
            "name": str(signal.name),
            "signal_date": signal_date.date().isoformat(),
            "signal_month": str(signal.signal_month),
            "kong_turn_bull_pattern": getattr(signal, "kong_turn_bull_pattern"),
            "three_day_kong_turn_bull": bool(getattr(signal, "three_day_kong_turn_bull")),
            "two_day_kong_turn_bull": bool(getattr(signal, "two_day_kong_turn_bull")),
            "signal_open": float(signal.signal_open),
            "signal_high": float(signal.signal_high),
            "signal_low": float(signal.signal_low),
            "signal_close": float(signal.signal_close),
            "entry_date": entry_date,
            "entry_price": entry_price,
            "entry_open": float(entry_bar["open"]),
            "entry_high": float(entry_bar["high"]),
            "entry_low": float(entry_bar["low"]),
            "entry_close": float(entry_bar["close"]),
        }

        for hold_day in HOLD_DAYS:
            exit_idx = signal_idx + hold_day
            if exit_idx >= len(daily_df):
                row[f"exit_date_{hold_day}d"] = pd.NA
                row[f"ret_{hold_day}d"] = pd.NA
                continue

            exit_bar = daily_df.iloc[exit_idx]
            row[f"exit_date_{hold_day}d"] = pd.Timestamp(daily_dates[exit_idx]).date().isoformat()
            row[f"ret_{hold_day}d"] = compute_return(float(exit_bar["close"]), entry_price)

        rows.append(row)

    result_df = pd.DataFrame(rows)
    if not result_df.empty:
        result_df = result_df.sort_values(["signal_date", "file_symbol"]).reset_index(drop=True)
    return result_df


def expand_groups(detail_df: pd.DataFrame) -> pd.DataFrame:
    if detail_df.empty:
        return pd.DataFrame()

    group_masks = [
        ("three_day_all", detail_df["three_day_kong_turn_bull"].fillna(False)),
        ("two_day_all", detail_df["two_day_kong_turn_bull"].fillna(False)),
        ("both", detail_df["three_day_kong_turn_bull"].fillna(False) & detail_df["two_day_kong_turn_bull"].fillna(False)),
        (
            "three_day_only",
            detail_df["three_day_kong_turn_bull"].fillna(False) & ~detail_df["two_day_kong_turn_bull"].fillna(False),
        ),
        (
            "two_day_only",
            detail_df["two_day_kong_turn_bull"].fillna(False) & ~detail_df["three_day_kong_turn_bull"].fillna(False),
        ),
    ]

    frames: list[pd.DataFrame] = []
    for group_name, mask in group_masks:
        subset = detail_df.loc[mask].copy()
        if subset.empty:
            continue
        subset["group_name"] = group_name
        frames.append(subset)
    if not frames:
        return pd.DataFrame()
    return pd.concat(frames, ignore_index=True)


def summarize_return_series(series: pd.Series) -> dict[str, object]:
    numeric = pd.to_numeric(series, errors="coerce").dropna()
    if numeric.empty:
        return {
            "sample_count": 0,
            "win_rate": pd.NA,
            "avg_return": pd.NA,
            "median_return": pd.NA,
            "avg_gain": pd.NA,
            "avg_loss": pd.NA,
        }

    gains = numeric[numeric > 0]
    losses = numeric[numeric <= 0]
    return {
        "sample_count": int(len(numeric)),
        "win_rate": float((numeric > 0).mean()),
        "avg_return": float(numeric.mean()),
        "median_return": float(numeric.median()),
        "avg_gain": float(gains.mean()) if not gains.empty else pd.NA,
        "avg_loss": float(losses.mean()) if not losses.empty else pd.NA,
    }


def build_summary(grouped_df: pd.DataFrame) -> pd.DataFrame:
    if grouped_df.empty:
        return pd.DataFrame()

    rows: list[dict[str, object]] = []
    for group_name, group_df in grouped_df.groupby("group_name", sort=False):
        for hold_day in HOLD_DAYS:
            rows.append(
                {
                    "scope": "overall",
                    "signal_month": pd.NA,
                    "group_name": group_name,
                    "holding_days": hold_day,
                    **summarize_return_series(group_df[f"ret_{hold_day}d"]),
                }
            )
        for signal_month, month_df in group_df.groupby("signal_month", sort=True):
            for hold_day in HOLD_DAYS:
                rows.append(
                    {
                        "scope": "monthly",
                        "signal_month": signal_month,
                        "group_name": group_name,
                        "holding_days": hold_day,
                        **summarize_return_series(month_df[f"ret_{hold_day}d"]),
                    }
                )

    return pd.DataFrame(rows).sort_values(
        ["scope", "signal_month", "group_name", "holding_days"],
        na_position="first",
    ).reset_index(drop=True)


def build_fill_summary(signal_df: pd.DataFrame, entry_df: pd.DataFrame) -> pd.DataFrame:
    grouped_signals = expand_groups(signal_df)
    grouped_entries = expand_groups(entry_df)
    rows: list[dict[str, object]] = []

    for scope, month in [("overall", pd.NA)] + [("monthly", value) for value in sorted(signal_df["signal_month"].dropna().unique())]:
        for group_name in ALL_GROUPS:
            signal_subset = grouped_signals[grouped_signals["group_name"] == group_name]
            entry_subset = grouped_entries[grouped_entries["group_name"] == group_name]
            if scope == "monthly":
                signal_subset = signal_subset[signal_subset["signal_month"] == month]
                entry_subset = entry_subset[entry_subset["signal_month"] == month]
            signal_count = len(signal_subset)
            entry_count = len(entry_subset)
            rows.append(
                {
                    "scope": scope,
                    "signal_month": month,
                    "group_name": group_name,
                    "signal_count": signal_count,
                    "filled_count": entry_count,
                    "fill_rate": float(entry_count / signal_count) if signal_count else pd.NA,
                }
            )
    return pd.DataFrame(rows)


def make_markdown_table(df: pd.DataFrame, columns: list[str], rename_map: dict[str, str] | None = None) -> str:
    if df.empty:
        return "无数据。"

    work_df = df.loc[:, columns].rename(columns=rename_map or {}).copy()
    headers = list(work_df.columns)
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for _, row in work_df.iterrows():
        cells = [str(row[column]) if not pd.isna(row[column]) else "-" for column in headers]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_summary_table(summary_df: pd.DataFrame, group_names: tuple[str, ...]) -> str:
    work_df = summary_df[summary_df["group_name"].isin(group_names)].copy()
    if work_df.empty:
        return "无数据。"

    work_df["样本数"] = work_df["sample_count"].astype("Int64").astype(str)
    work_df["胜率"] = work_df["win_rate"].apply(format_pct)
    work_df["平均收益"] = work_df["avg_return"].apply(format_pct)
    work_df["中位收益"] = work_df["median_return"].apply(format_pct)
    return make_markdown_table(
        work_df,
        columns=["group_name", "holding_days", "样本数", "胜率", "平均收益", "中位收益"],
        rename_map={"group_name": "分组", "holding_days": "持有天数"},
    )


def render_pairwise_table(summary_df: pd.DataFrame, group_a: str, group_b: str) -> str:
    work_df = summary_df[summary_df["group_name"].isin([group_a, group_b])].copy()
    if work_df.empty:
        return "无数据。"

    pivot_df = work_df.pivot(index="holding_days", columns="group_name")
    rows: list[dict[str, object]] = []
    for hold_day in HOLD_DAYS:
        if hold_day not in pivot_df.index:
            continue
        a_avg = pivot_df.at[hold_day, ("avg_return", group_a)] if ("avg_return", group_a) in pivot_df.columns else pd.NA
        b_avg = pivot_df.at[hold_day, ("avg_return", group_b)] if ("avg_return", group_b) in pivot_df.columns else pd.NA
        a_win = pivot_df.at[hold_day, ("win_rate", group_a)] if ("win_rate", group_a) in pivot_df.columns else pd.NA
        b_win = pivot_df.at[hold_day, ("win_rate", group_b)] if ("win_rate", group_b) in pivot_df.columns else pd.NA
        rows.append(
            {
                "holding_days": hold_day,
                f"{group_a}_avg": format_pct(a_avg),
                f"{group_a}_win": format_pct(a_win),
                f"{group_b}_avg": format_pct(b_avg),
                f"{group_b}_win": format_pct(b_win),
                "avg_diff": format_pct(float(a_avg) - float(b_avg)) if not pd.isna(a_avg) and not pd.isna(b_avg) else "-",
            }
        )
    return make_markdown_table(
        pd.DataFrame(rows),
        columns=["holding_days", f"{group_a}_avg", f"{group_a}_win", f"{group_b}_avg", f"{group_b}_win", "avg_diff"],
        rename_map={
            "holding_days": "持有天数",
            f"{group_a}_avg": f"{group_a}平均",
            f"{group_a}_win": f"{group_a}胜率",
            f"{group_b}_avg": f"{group_b}平均",
            f"{group_b}_win": f"{group_b}胜率",
            "avg_diff": f"平均差({group_a}-{group_b})",
        },
    )


def render_fill_table(fill_df: pd.DataFrame) -> str:
    work_df = fill_df.copy()
    if work_df.empty:
        return "无数据。"
    work_df["fill_rate_text"] = work_df["fill_rate"].apply(format_pct)
    return make_markdown_table(
        work_df,
        columns=["group_name", "signal_count", "filled_count", "fill_rate_text"],
        rename_map={
            "group_name": "分组",
            "signal_count": "信号数",
            "filled_count": "成交数",
            "fill_rate_text": "成交率",
        },
    )


def build_report(
    signal_df: pd.DataFrame,
    entry_df: pd.DataFrame,
    summary_df: pd.DataFrame,
    fill_df: pd.DataFrame,
    output_paths: dict[str, Path],
) -> str:
    overall_summary = summary_df[summary_df["scope"] == "overall"].copy()
    overall_fill = fill_df[fill_df["scope"] == "overall"].copy()
    months = sorted(signal_df["signal_month"].dropna().unique())

    lines: list[str] = []
    lines.append("# 2反转 / 3反转 次日50%K线位置买入收益统计")
    lines.append("")
    lines.append("## 口径")
    lines.append("")
    lines.append("- 信号池：沿用 `weekly_bullish_kong_turn_bull_forward_compare_detail_2026-04-01_to_2026-06-30.csv`。")
    lines.append("- 买入价：信号日这根日K的 50% 位置，即 `signal_low + (signal_high - signal_low) * 0.5`。")
    lines.append("- 成交判定：信号后第一个交易日 `low <= 买入价 <= high`，只统计实际触达的样本。")
    lines.append("- 持有 1 日：从买入价到买入当天收盘；持有 2-5 日：从买入价到之后第 2-5 个交易日收盘。")
    lines.append("")
    lines.append("## 成交概览")
    lines.append("")
    lines.append(f"- 原始信号数：{len(signal_df)}")
    lines.append(f"- 50%位置成交数：{len(entry_df)}")
    lines.append(f"- 整体成交率：{format_pct(len(entry_df) / len(signal_df)) if len(signal_df) else '-'}")
    lines.append("")
    lines.append(render_fill_table(overall_fill[overall_fill["group_name"].isin(ALL_GROUPS)]))
    lines.append("")
    lines.append("## 整体：2反转 vs 3反转")
    lines.append("")
    lines.append(render_pairwise_table(overall_summary, "two_day_all", "three_day_all"))
    lines.append("")
    lines.append("## 整体：纯2反转 vs 纯3反转")
    lines.append("")
    lines.append(render_pairwise_table(overall_summary, "two_day_only", "three_day_only"))
    lines.append("")
    lines.append("## 整体分组表现")
    lines.append("")
    lines.append(render_summary_table(overall_summary, ALL_GROUPS))
    lines.append("")

    for month in months:
        month_summary = summary_df[(summary_df["scope"] == "monthly") & (summary_df["signal_month"] == month)].copy()
        month_fill = fill_df[(fill_df["scope"] == "monthly") & (fill_df["signal_month"] == month)].copy()
        lines.append(f"## {month}")
        lines.append("")
        lines.append(render_fill_table(month_fill[month_fill["group_name"].isin(ALL_GROUPS)]))
        lines.append("")
        lines.append(render_pairwise_table(month_summary, "two_day_all", "three_day_all"))
        lines.append("")

    lines.append("## 输出文件")
    lines.append("")
    for label, path in output_paths.items():
        lines.append(f"- {label}: `{path.name}`")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    ensure_project_dirs()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    signal_df = pd.read_csv(
        args.input,
        dtype={"file_symbol": str, "symbol": str},
    )
    entry_df = build_entry_detail(signal_df=signal_df, data_root=Path(args.data_root))
    grouped_entry_df = expand_groups(entry_df)
    summary_df = build_summary(grouped_entry_df)
    fill_df = build_fill_summary(signal_df=signal_df, entry_df=entry_df)

    suffix = args.input.stem.replace("weekly_bullish_kong_turn_bull_forward_compare_detail_", "")
    output_paths = {
        "entry_detail": output_dir / f"weekly_bullish_kong_turn_bull_half_k_entry_detail_{suffix}.csv",
        "fill_summary": output_dir / f"weekly_bullish_kong_turn_bull_half_k_entry_fill_{suffix}.csv",
        "return_summary": output_dir / f"weekly_bullish_kong_turn_bull_half_k_entry_summary_{suffix}.csv",
        "report": output_dir / f"weekly_bullish_kong_turn_bull_half_k_entry_report_{suffix}.md",
    }

    entry_df.to_csv(output_paths["entry_detail"], index=False, encoding="utf-8-sig")
    fill_df.to_csv(output_paths["fill_summary"], index=False, encoding="utf-8-sig")
    summary_df.to_csv(output_paths["return_summary"], index=False, encoding="utf-8-sig")
    output_paths["report"].write_text(
        build_report(
            signal_df=signal_df,
            entry_df=entry_df,
            summary_df=summary_df,
            fill_df=fill_df,
            output_paths=output_paths,
        ),
        encoding="utf-8",
    )

    print(f"signal_rows={len(signal_df)}")
    print(f"entry_rows={len(entry_df)}")
    print(f"entry_detail={output_paths['entry_detail']}")
    print(f"summary={output_paths['return_summary']}")
    print(f"report={output_paths['report']}")
    if not summary_df.empty:
        print(summary_df[(summary_df['scope'] == 'overall') & (summary_df['group_name'].isin(['two_day_all', 'three_day_all']))].to_string(index=False))


if __name__ == "__main__":
    main()
